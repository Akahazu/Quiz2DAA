import random
from game.settings import *


class Map:
    def __init__(self, walls, costs=None):
        self.walls = walls
        self.costs = costs if costs is not None else self._default_costs()

    def _default_costs(self):
        return [
            [1 if not self.is_wall(x, y) else 0 for x in range(GRID_WIDTH)]
            for y in range(GRID_HEIGHT)
        ]

    def is_wall(self, x, y):
        return self.walls[y][x] == 1

    def get_cost(self, x, y):
        if self.is_wall(x, y):
            return float("inf")
        return self.costs[y][x]

    @classmethod
    def from_seed(cls, walls, seed):
        # Generate random costs (1..5) for non-wall cells using the given seed.
        rng = random.Random(seed)
        costs = [[0] * GRID_WIDTH for _ in range(GRID_HEIGHT)]
        for y in range(GRID_HEIGHT):
            for x in range(GRID_WIDTH):
                if walls[y][x] == 0:  # not a wall
                    costs[y][x] = rng.randint(1, 5)
                else:
                    costs[y][x] = 0  # walls have cost 0 (but get_cost returns inf)
        return cls(walls, costs)


